using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;

namespace AjBoilerplate.Auth.Sql;

/// <summary>
/// System of record for sessions and for the outbox of session-ended events they produce (schema <c>auth</c>). Redis is a cache in front
/// of the sessions. The outbox lives here because it must be written in the same transaction as the session delete it reports.
/// </summary>
public sealed class AuthDbContext : DbContext
{
    public const string Schema = "auth";

    /// <summary>Migration history lives in the service's own schema, so it never collides with another service in a shared database.</summary>
    public const string HistoryTable = "__EFMigrationsHistory";

    public AuthDbContext(DbContextOptions<AuthDbContext> options)
        : base(options)
    {
    }

    internal DbSet<SessionRow> Sessions => Set<SessionRow>();

    internal DbSet<SessionEndedEventRow> SessionEndedOutbox => Set<SessionEndedEventRow>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        modelBuilder.Entity<SessionRow>(e =>
        {
            e.ToTable("Sessions", Schema);
            e.HasKey(x => x.SessionKey);

            // SessionIds.StorageKey is base64url SHA-256: exactly 43 ASCII characters. A fixed-width column of
            // exactly that width never pads, so a key read back from the table is the key that was written.
            // Binary collation: two keys differing only in case are never the same row.
            e.Property(x => x.SessionKey).HasColumnType("char(43)").UseCollation("Latin1_General_BIN2");
            e.Property(x => x.Subject).HasMaxLength(256).IsRequired();
            e.Property(x => x.ClientId).HasMaxLength(256).IsRequired();
            e.Property(x => x.KeycloakJwt).IsRequired();

            // Same shape and collation as SessionKey, which is what it holds.
            e.Property(x => x.RefreshVia).HasColumnType("char(43)").UseCollation("Latin1_General_BIN2");

            e.HasIndex(x => x.Subject).HasDatabaseName("IX_Sessions_Subject");
            e.HasIndex(x => x.ExpiresAt).HasDatabaseName("IX_Sessions_ExpiresAt");
        });

        modelBuilder.Entity<SessionEndedEventRow>(e =>
        {
            e.ToTable("SessionEndedOutbox", Schema);
            e.HasKey(x => x.EventId);

            // Generated by the writer (a v7 GUID), never by the database: it is the idempotency key the portal sees, so it must be
            // known before the row exists.
            e.Property(x => x.EventId).ValueGeneratedNever();
            e.Property(x => x.SessionId).HasColumnType("char(32)").IsRequired();

            // NO SUBJECT, deliberately: the event carries no user identifier. The portal pairs it with its own "session created"
            // row by SessionId, and that row already names the user.
            e.Property(x => x.ClientId).HasMaxLength(256).IsRequired();
            e.Property(x => x.Reason).HasColumnType("varchar(32)").IsRequired();
            e.Property(x => x.Detail).HasColumnType("varchar(64)").IsRequired();
            e.Property(x => x.CorrelationId).HasColumnType("varchar(64)");
            e.Property(x => x.LastOutcome).HasColumnType("varchar(64)");

            // The dispatcher's query: pending rows, by due time. Filtered so settled rows, which are most of the table between
            // purges, are not in the index at all.
            e.HasIndex(x => x.NextAttemptAt)
                .HasDatabaseName("IX_SessionEndedOutbox_Pending")
                .HasFilter("[DeliveredAt] IS NULL AND [AbandonedAt] IS NULL");
        });
    }
}

/// <summary>Lets <c>dotnet ef</c> build a context without running the host. Reads <c>AUTH_DB_CONNECTION</c>.</summary>
public sealed class AuthDbContextFactory : IDesignTimeDbContextFactory<AuthDbContext>
{
    public const string ConnectionEnvironmentVariable = "AUTH_DB_CONNECTION";

    public AuthDbContext CreateDbContext(string[] args)
    {
        var connection = Environment.GetEnvironmentVariable(ConnectionEnvironmentVariable);
        var options = new DbContextOptionsBuilder<AuthDbContext>()
            .UseSqlServer(
                string.IsNullOrWhiteSpace(connection) ? "Server=(localdb)\\mssqllocaldb;Database=auth" : connection,
                sql => sql.MigrationsHistoryTable(AuthDbContext.HistoryTable, AuthDbContext.Schema))
            .Options;
        return new AuthDbContext(options);
    }
}
